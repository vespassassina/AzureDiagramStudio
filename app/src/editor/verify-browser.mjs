import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from '@playwright/test'
import { createServer } from 'vite'
import { assertCatalogSearch, catalogCoverage, verifyCatalogPalette } from '../../scripts/verify-catalog.mjs'

const root = fileURLToPath(new URL('../../', import.meta.url))
const output = fileURLToPath(new URL('./evidence/', import.meta.url))
const server = await createServer({ root, server: { host: '127.0.0.1', port: 0, strictPort: true, open: false } })
await server.listen()
const url = `http://127.0.0.1:${server.httpServer.address().port}/src/editor/Editor.harness.html`
const reports = []
let browser
async function state(page) { return page.evaluate(() => window.__editorHarness) }
async function showProperties(page) { if (!(await page.locator('.inspector').evaluate(element => element.classList.contains('open')))) await page.getByRole('button', { name: 'Open properties', exact: true }).click() }
async function showLibrary(page) { if (!(await page.locator('.library').evaluate(element => element.classList.contains('open')))) await page.getByRole('button', { name: 'Open component library', exact: true }).click() }
async function closePanels(page) {
  if (await page.getByRole('button', { name: 'Close component library', exact: true }).isVisible()) await page.getByRole('button', { name: 'Close component library', exact: true }).click()
  if (await page.getByRole('button', { name: 'Close properties', exact: true }).isVisible()) await page.getByRole('button', { name: 'Close properties', exact: true }).click()
}
async function clickNode(page, id) {
  await page.locator(`.react-flow__node[data-id="${id}"]`).click({ position: { x: 20, y: 20 } })
}
async function clickEdge(page, id) {
  const point = await page.locator(`.react-flow__edge[data-id="${id}"] .react-flow__edge-interaction`).evaluate(path => {
    const local = path.getPointAtLength(path.getTotalLength() * .23)
    const screen = new DOMPoint(local.x, local.y).matrixTransform(path.getScreenCTM())
    return { x: screen.x, y: screen.y }
  })
  await page.mouse.click(point.x, point.y)
}
async function checkBounds(page, viewport) {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'No horizontal page overflow')
  const controls = await page.locator('.topbar button, .tool-rail button, .canvas-toolbar button, .zoom-controls button, .mobile-controls button, .canvas-selection-toolbar button').evaluateAll(buttons => buttons.map(button => {
    const rect = button.getBoundingClientRect()
    return { label: button.getAttribute('aria-label'), x: rect.x, y: rect.y, right: rect.right, bottom: rect.bottom, width: rect.width, height: rect.height }
  }))
  for (const control of controls.filter(control => control.width && control.height)) assert.ok(control.x >= -.5 && control.y >= -.5 && control.right <= viewport.width + .5 && control.bottom <= viewport.height + .5, `Clipped control: ${JSON.stringify(control)}`)
}

